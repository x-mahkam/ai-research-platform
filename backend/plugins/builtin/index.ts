/**
 * System Binary Resolver Utility
 * Checks whether a scientific software executable exists on the host machine in PATH or standard system paths.
 */
function findExecutable(binaryName: string, envVar?: string, defaultDirs: string[] = []): string | null {
  if (envVar && process.env[envVar]) {
    const envPath = process.env[envVar]!;
    if (fs.existsSync(envPath)) return envPath;
    const candidate = path.join(envPath, 'bin', binaryName);
    if (fs.existsSync(candidate)) return candidate;
  }

  const pathDirs = (process.env.PATH || '').split(path.delimiter);
  for (const dir of [...pathDirs, ...defaultDirs]) {
    const fullPath = path.join(dir, binaryName);
    const fullPathExe = path.join(dir, `${binaryName}.exe`);
    if (fs.existsSync(fullPath)) return fullPath;
    if (fs.existsSync(fullPathExe)) return fullPathExe;
  }

  return null;
}

