    const inputDir = path.join(workspacePath, 'input');
    if (!fs.existsSync(inputDir)) fs.mkdirSync(inputDir, { recursive: true });
    fs.writeFileSync(path.join(inputDir, 'dft_transport.py'), pyContent, 'utf-8');
